"""Writes src/runtime_export_nids.inc: "NID#library" of every function the runtime exports by name.

The runtime's RuntimeExport tables name functions ("scePadInit"); a game imports them by NID (a
hash of the name) scoped by library. runtime_symbol() used to know only the imports listed in
import_names.inc, written from God of War III's imports, so a function the runtime implements but
that game never imported was not found for another game. This file adds every exported name, in
the libraries that export it on the PS4 (tools/issn/ps4_nid_libraries.tsv, from shadPS4): the same
name in another library (gettimeofday in libc and in libkernel) can be another contract.

usage: python tools/issn/gen_export_nids.py [--check]
--check: exit 1 when the file is out of date (tests/test_export_nids.py).
"""
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / 'scripts'))
from prepare import nid  # noqa: E402

OUTPUT = REPO / 'src' / 'runtime_export_nids.inc'
LIBRARIES = Path(__file__).with_name('ps4_nid_libraries.tsv')
TABLE = re.compile(r'RuntimeExport\s+\w+\s*\[\s*\]\s*=\s*\{(.*?)\n\s*\};', re.S)
ENTRY = re.compile(r'\{\s*"([A-Za-z_][A-Za-z0-9_]*)"\s*,')


def exported_names():
    names = set()
    for path in sorted((REPO / 'src').glob('*.c')):
        for table in TABLE.findall(path.read_text(encoding='utf-8', errors='replace')):
            names.update(ENTRY.findall(table))
    return sorted(names)


def libraries():
    """{NID: libraries}; libScePosix is libkernel for the runtime (runtime.c canonical_name)."""
    found = {}
    for line in LIBRARIES.read_text(encoding='utf-8').splitlines():
        if not line.strip() or line.startswith('#'):
            continue
        code, library = line.split('\t')
        found.setdefault(code, set()).add('libkernel' if library == 'libScePosix' else library)
    return found


def render(names):
    known = libraries()
    lines = ['/* Generated by tools/issn/gen_export_nids.py: "NID#library" of each name in the runtime\'s',
             ' * RuntimeExport tables, in the libraries that export it on the PS4. */']
    lines += [f'{{"{nid(name)}#{library}","{name}"}},' for name in names for library in sorted(known.get(nid(name), ()))]
    return '\n'.join(lines) + '\n'


def main():
    text = render(exported_names())
    if '--check' in sys.argv[1:]:
        current = OUTPUT.read_text(encoding='utf-8') if OUTPUT.is_file() else ''
        if current != text:
            print(f'{OUTPUT.relative_to(REPO)} is out of date: run python tools/issn/gen_export_nids.py')
            return 1
        return 0
    OUTPUT.write_text(text, encoding='utf-8')
    print(f'{OUTPUT.relative_to(REPO)}: {text.count(chr(10)) - 2} entries for {len(exported_names())} names')
    return 0


if __name__ == '__main__':
    sys.exit(main())
